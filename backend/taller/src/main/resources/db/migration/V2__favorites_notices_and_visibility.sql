CREATE TABLE favorites (
    owner_id bigint NOT NULL,
    target_type varchar(12) NOT NULL CHECK (target_type IN ('PRODUCT', 'COLLECTION')),
    target_id bigint NOT NULL,
    PRIMARY KEY (owner_id, target_type, target_id)
);

CREATE TABLE hidden_requests (
    owner_id bigint NOT NULL,
    request_id bigint NOT NULL REFERENCES commercial_requests(id),
    PRIMARY KEY (owner_id, request_id)
);

CREATE TABLE notices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id bigint,
    recipient_role varchar(8),
    target_category varchar(30),
    title varchar(150) NOT NULL,
    body varchar(500) NOT NULL,
    destination varchar(100) NOT NULL,
    date bigint NOT NULL,
    event_key varchar(100) NOT NULL UNIQUE,
    CHECK ((recipient_id IS NOT NULL AND recipient_role IS NULL)
        OR (recipient_id IS NULL AND recipient_role IS NOT NULL))
);

CREATE TABLE notice_receipts (
    owner_id bigint NOT NULL,
    notice_id bigint NOT NULL REFERENCES notices(id),
    read boolean NOT NULL DEFAULT false,
    delivered boolean NOT NULL DEFAULT false,
    dismissed boolean NOT NULL DEFAULT false,
    PRIMARY KEY (owner_id, notice_id)
);

