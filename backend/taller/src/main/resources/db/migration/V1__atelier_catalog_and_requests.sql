CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 5) PRIMARY KEY,
    name varchar(100) NOT NULL,
    width_cm double precision NOT NULL CHECK (width_cm > 0),
    length_cm double precision NOT NULL CHECK (length_cm > 0),
    material varchar(100) NOT NULL,
    price bigint NOT NULL CHECK (price >= 0),
    campaign_category varchar(30) NOT NULL,
    description varchar(2000) NOT NULL DEFAULT '',
    availability varchar(20) NOT NULL DEFAULT 'AVAILABLE',
    active boolean NOT NULL DEFAULT true,
    stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0)
);

CREATE TABLE atelier_collections (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    name varchar(100) NOT NULL,
    description varchar(2000) NOT NULL
);

CREATE TABLE collection_products (
    collection_id bigint NOT NULL REFERENCES atelier_collections(id),
    product_id bigint NOT NULL REFERENCES products(id),
    PRIMARY KEY (collection_id, product_id)
);

CREATE TABLE campaigns (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    collection_id bigint NOT NULL REFERENCES atelier_collections(id),
    starts_on varchar(10) NOT NULL,
    ends_on varchar(10) NOT NULL,
    published boolean NOT NULL,
    target_category varchar(30)
);

CREATE TABLE commercial_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date bigint NOT NULL,
    anonymized_client varchar(48) NOT NULL,
    total bigint NOT NULL CHECK (total >= 0),
    status varchar(20) NOT NULL,
    product_id bigint NOT NULL REFERENCES products(id),
    intention varchar(20) NOT NULL,
    comment varchar(500),
    campaign_category varchar(30),
    owner_id bigint NOT NULL,
    customization varchar(1000),
    campaign_id bigint REFERENCES campaigns(id),
    source_collection_id bigint REFERENCES atelier_collections(id),
    journey_id varchar(100),
    agreed_total bigint,
    agreed_at bigint,
    quantity integer NOT NULL CHECK (quantity > 0),
    operation_key varchar(100) NOT NULL,
    operation_hash char(64) NOT NULL,
    UNIQUE (owner_id, operation_key)
);

CREATE INDEX requests_owner ON commercial_requests(owner_id, id);

CREATE TABLE stock_movements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES products(id),
    quantity_delta integer NOT NULL CHECK (quantity_delta <> 0),
    stock_after integer NOT NULL CHECK (stock_after >= 0),
    type varchar(20) NOT NULL,
    date bigint NOT NULL,
    actor_id bigint NOT NULL,
    note varchar(250) NOT NULL,
    request_id bigint UNIQUE REFERENCES commercial_requests(id),
    operation_key varchar(100),
    operation_hash char(64),
    UNIQUE (actor_id, operation_key)
);

CREATE TABLE write_guards (
    operation varchar(24) PRIMARY KEY
);

