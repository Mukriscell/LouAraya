CREATE TABLE profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY,
    name varchar(80) NOT NULL,
    alias varchar(40) NOT NULL UNIQUE,
    password_hash varchar(72) NOT NULL,
    role varchar(8) NOT NULL CHECK (role IN ('CLIENT', 'ADMIN')),
    avatar integer NOT NULL CHECK (avatar BETWEEN 0 AND 7),
    contact varchar(100) NOT NULL DEFAULT '',
    notifications_enabled boolean NOT NULL DEFAULT true,
    preferred_category varchar(30)
);

CREATE TABLE sessions (
    token_hash char(64) PRIMARY KEY,
    profile_id bigint NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    expires_at bigint NOT NULL
);

CREATE INDEX sessions_expiry ON sessions (expires_at);
